"""Deterministic atlas packing. Full 480px cells, including padding, are displayed.
Usage: python scripts/icons/pack.py (Pillow)
"""
from pathlib import Path
import json
from PIL import Image,ImageDraw
ROOT=Path(__file__).resolve().parents[2]
entries=json.loads((ROOT/'assets-src/icons.json').read_text(encoding='utf-8'))
out=ROOT/'public/assets/icons';out.mkdir(parents=True,exist_ok=True)
atlases={};mapping={};sources={};report=[]
preview=Image.new('RGBA',(600,((len(entries)+9)//10)*86),'#eee4cc');draw=ImageDraw.Draw(preview)
for n,e in enumerate(entries):
 raw=e['raw']
 if raw not in sources:sources[raw]=Image.open(ROOT/f'assets-src/icons/raw/{raw}.png').convert('RGBA')
 im=sources[raw];w,h=im.size
 assert w/3==h/2,(raw,'must have equal 3x2 cells',im.size)
 cw=w//3;ch=h//2;i=e['cell'];crop=im.crop(((i%3)*cw,(i//3)*ch,(i%3+1)*cw,(i//3+1)*ch))
 alpha=crop.getchannel('A');box=alpha.point(lambda a:255 if a>16 else 0).getbbox()
 assert box,(raw,i,'empty icon')
 assert box[0]>1 and box[1]>1 and box[2]<cw-1 and box[3]<ch-1,(raw,i,'art touches crop edge',box)
 art=crop.crop(box);art.thumbnail((384,384),Image.Resampling.LANCZOS)
 tile=Image.new('RGBA',(480,480));tile.alpha_composite(art,((480-art.width)//2,(480-art.height)//2))
 bound=tile.getchannel('A').getbbox();assert min(bound[0],bound[1],480-bound[2],480-bound[3])>=48
 sheet=e['sheet'];index=e['slot']
 if sheet not in atlases:atlases[sheet]=Image.new('RGBA',(1920,1440));mapping[sheet]=['']*12
 assert not mapping[sheet][index],(sheet,index,'duplicate slot')
 mapping[sheet][index]=e['id'];atlases[sheet].alpha_composite(tile,((index%4)*480,(index//4)*480))
 e.update(file=f'icons/{sheet}.webp',index=index,x=index%4*480,y=index//4*480)
 preview.alpha_composite(tile.resize((40,40),Image.Resampling.LANCZOS),((n%10)*60+10,(n//10)*86))
 preview.alpha_composite(tile.resize((24,24),Image.Resampling.LANCZOS),((n%10)*60+18,(n//10)*86+42))
 draw.text(((n%10)*60,(n//10)*86+68),e['id'][:10],fill='#221b14')
for sheet,im in atlases.items():
 dest=out/f'{sheet}.webp'
 for quality in [82,76,68,60,52]:
  im.save(dest,quality=quality,method=6)
  if dest.stat().st_size<400000:break
 assert dest.stat().st_size<400000,(sheet,'exceeds 400KB')
 report.append((sheet,dest.stat().st_size))
(out/'manifest.json').write_text(json.dumps({'cell':480,'columns':4,'rows':3,'padding':48,'icons':entries},ensure_ascii=False,indent=2),encoding='utf-8')
(ROOT/'src/spriteSheets.gen.ts').write_text('// Generated by scripts/icons/pack.py. Do not edit.\nexport const spriteSheets:Record<string,readonly string[]> = '+json.dumps(mapping,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
preview.save(out/'readability-preview.png')
print('Packed',len(entries),'icons; full-cell padding >=48px.',report)
